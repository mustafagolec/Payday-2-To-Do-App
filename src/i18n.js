export function makeT (lang) {
  const table = dict[lang] || dict.tr
  return (key, vars) => {
    let text = table[key] ?? dict.tr[key] ?? key
    if (vars) {
      for (const name of Object.keys(vars)) {
        text = text.replaceAll(`{${name}}`, String(vars[name]))
      }
    }
    return text
  }
}
